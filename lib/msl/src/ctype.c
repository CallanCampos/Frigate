#define BLANK_PRINT (__ctype_space | __ctype_blank | __ctype_print)
#define PUNCT (__ctype_punct | __ctype_print | __ctype_graph)
#define DIGIT (__ctype_xdigit | __ctype_digit | __ctype_print | __ctype_graph)
#define XUPPER (__ctype_xdigit | __ctype_upper | __ctype_alpha | __ctype_print | __ctype_graph)
#define UPPER (__ctype_upper | __ctype_alpha | __ctype_print | __ctype_graph)
#define XLOWER (__ctype_xdigit | __ctype_lower | __ctype_alpha | __ctype_print | __ctype_graph)
