PMSInputData *PMSIData_Create(u32 heapId, const PMSIParam *param) {
    PMSInputData *data;
    int i;

    data = GFL_HeapAllocate(heapId, sizeof(PMSInputData), FALSE, "pms_input_data.c", 88);
    data->param = param;
    data->wordBank = PMSWordBank_Create(heapId);
    for (i = 0; i < PMSI_WORD_FLAG_SIZE; i++) {
        data->wordEnableFlags[i] = 0;
    }
    SetupCategoryWords(data);
    SetupInitialWords(data);
    return data;
}

void PMSIData_Delete(PMSInputData *data) {
    if (data) {
        PMSWordBank_Free(data->wordBank);
        GFL_HeapFree(data);
    }
}

static void SetupCategoryWords(PMSInputData *data) {
    int i, pos;

    for (i = 0, pos = 0; i < PMSI_CATEGORY_COUNT; i++) {
        data->categoryWordPos[i] = pos;
        data->categoryWordCount[i] = sCategoryCountup[i].func(data, sCategoryCountup[i].words,
                                                              sCategoryCountup[i].count, &data->categoryWords[pos]);
        pos += data->categoryWordCount[i];
    }
}

static inline void SetWordEnableFlag(PMSInputData *data, u32 word) {
    data->wordEnableFlags[word >> 3] |= 1 << (word & 7);
}

static inline BOOL GetWordEnableFlag(const PMSInputData *data, u32 word) {
    return (data->wordEnableFlags[word >> 3] & (1 << (word & 7))) != 0;
}

static u32 CountupPokemon(PMSInputData *data, const u16 *src, u32 count, u16 *dst) {
    PokeDexSave *dex;
    u32 i, n;

    dex = PMSIParam_GetPokeDex(data->param);
    n = 0;
    for (i = 0; i < count; i++) {
        if (PokeDex_IsSeen(dex, src[i])) {
            SetWordEnableFlag(data, src[i]);
            *dst++ = src[i];
            n++;
        }
    }
    return n;
}

static u32 CountupMoves(PMSInputData *data, const u16 *src, u32 count, u16 *dst) {
    u32 i;

    if (func_02029a74(data->param)) {
        for (i = 0; i < count; i++) {
            SetWordEnableFlag(data, *src);
            *dst++ = *src++;
        }
        return count;
    } else {
        return 0;
    }
}

static u32 CountupGreetings(PMSInputData *data, const u16 *src, u32 count, u16 *dst) {
    PMSWordSave *save;
    u16 first, last;
    u32 i, n;

    save = PMSIParam_GetWordSave(data->param);
    first = PMSWord_FromMessage(PMS_GMM_GREETINGS, 0);
    last = first + PMS_LANGUAGE_GREETING_COUNT - 1;
    n = 0;
    for (i = 0; i < count; i++) {
        if (src[i] >= first && src[i] <= last) {
            if (PMSWordSave_GetLanguageFlag(save, src[i] - first) == FALSE) {
                continue;
            }
        }
        SetWordEnableFlag(data, src[i]);
        *dst++ = src[i];
        n++;
    }
    return n;
}

static u32 CountupNumbers(PMSInputData *data, const u16 *src, u32 count, u16 *dst) {
    u32 i, n;

    if (PMSIParam_HasNumbers(data->param) == FALSE) {
        return 0;
    }
    for (i = 0, n = 0; i < count; i++) {
        SetWordEnableFlag(data, src[i]);
        *dst++ = PMS_WORD_FIRST_NUMBER + i;
        n++;
    }
    return n;
}

static u32 CountupDefault(PMSInputData *data, const u16 *src, u32 count, u16 *dst) {
    u32 i;

    for (i = 0; i < count; i++) {
        if (*src == PMS_WORD_DUP) {
            u32 dup;

            src++;
            dup = *src++;
            while (dup) {
                SetWordEnableFlag(data, *src++);
                dup--;
            }
            *dst = src[-1];
        } else {
            SetWordEnableFlag(data, *src);
            *dst = *src++;
        }
        dst++;
    }
    return count;
}

static void SetupInitialWords(PMSInputData *data) {
    u32 i, pos = 0;

    for (i = 0; i < PMSI_INITIAL_COUNT; i++) {
        data->initialWordPos[i] = pos;
        data->initialWordCount[i] = CountupInitialWords(data, sInitialWords[i], data->initialWords, pos);
        pos += data->initialWordCount[i];
    }
}

static u32 CountupInitialWords(const PMSInputData *data, const u16 *src, u16 *dst, u32 pos) {
    u32 n = 0;

    while (*src != PMS_WORD_END) {
        if (*src == PMS_WORD_DUP) {
            u32 dup, i;

            src++;
            dup = *src++;
            for (i = 0; i < dup; i++) {
                if (GetWordEnableFlag(data, src[i])) {
                    dst[pos++] = src[i];
                    n++;
                    break;
                }
            }
            src += dup;
        } else {
            if (GetWordEnableFlag(data, *src)) {
                dst[pos++] = *src;
                n++;
            }
            src++;
        }
    }
    return n;
}

