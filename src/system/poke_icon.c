u16 PokeIcon_PackSpecies(u32 species, u32 form, u32 sex) {
    if (species == SPECIES_UNOWN || species == SPECIES_ARCEUS) {
        return species | ((form & 0x3f) << POKEICON_PACK_FORM_SHIFT);
    }
    return species | ((form & 0xf) << POKEICON_PACK_FORM_SHIFT) | ((sex & 3) << POKEICON_PACK_SEX_SHIFT);
}

void PokeIcon_UnpackSpecies(int packed, u32 *species, u32 *form, u32 *sex) {
    *species = packed & POKEICON_PACK_SPECIES_MASK;
    if (*species == SPECIES_UNOWN || *species == SPECIES_ARCEUS) {
        *form = (packed >> POKEICON_PACK_FORM_SHIFT) & 0x3f;
        *sex = 0;
    } else {
        *form = (packed >> POKEICON_PACK_FORM_SHIFT) & 0xf;
        *sex = (packed >> POKEICON_PACK_SEX_SHIFT) & 3;
    }
    if (*species >= SPECIES_EGG) {
        *species = 0;
        *form = 0;
        *sex = 0;
    }
}
