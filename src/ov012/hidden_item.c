// clang-format on

u16 GetHiddenItemNoBySCRID(u16 scrId) {
    if (scrId < HIDDEN_ITEM_SCRIPT_START || scrId > HIDDEN_ITEM_SCRIPT_END) {
        return 0;
    }
    return scrId - HIDDEN_ITEM_SCRIPT_START;
}

u16 GetHiddenItemEventFlagNoBySCRID(u16 scrId) {
    return HIDDEN_ITEMS[GetHiddenItemNoBySCRID(scrId)].index + HIDDEN_ITEM_FLAG_START;
}

// Brings back a fifth of the hidden items that come back, once a day
void TryClearRepeatableHiddenItemFlags(EventWork *eventWork) {
    u32 i;
    const HiddenItem *item;

    if (EventWork_GetHiddenItemRespawnFlag(eventWork)) {
        for (i = 0; i < HIDDEN_ITEM_COUNT; i++) {
            item = &HIDDEN_ITEMS[i];
            if (item->respawn && GFL_RandomLC(100) < 20) {
                EventWork_FlagReset(eventWork, item->index + HIDDEN_ITEM_FLAG_START);
            }
        }
    }
}

const HiddenItem *func_ov012_0215f2c4(u16 *count) {
    *count = HIDDEN_ITEM_COUNT;
    return HIDDEN_ITEMS;
}
